inline constexpr DWORD DisplayWidth = 1280;
inline constexpr DWORD DisplayHeight = 800;
inline constexpr DWORD DisplayRefresh = 60;
inline constexpr DWORD TotalWidth = 1440;
inline constexpr DWORD TotalHeight = 825;
inline constexpr UINT64 PixelRate = UINT64{TotalWidth} * TotalHeight * DisplayRefresh;

inline DISPLAYCONFIG_VIDEO_SIGNAL_INFO DisplaySignal(bool monitor)
{
    DISPLAYCONFIG_VIDEO_SIGNAL_INFO signal = {};
    signal.activeSize = {DisplayWidth, DisplayHeight};
    signal.totalSize = {TotalWidth, TotalHeight};
    signal.vSyncFreq = {DisplayRefresh, 1};
    signal.hSyncFreq = {DisplayRefresh * TotalHeight, 1};
    signal.pixelRate = PixelRate;
    signal.AdditionalSignalInfo.videoStandard = 255;
    signal.AdditionalSignalInfo.vSyncFreqDivider = monitor ? 0 : 1;
    signal.scanLineOrdering = DISPLAYCONFIG_SCANLINE_ORDERING_PROGRESSIVE;
    return signal;
}
